export function resolveStyle3DConfig(
  preset: StylePreset3D = 'cinematic_3d',
  custom?: Partial<Custom3DStyleConfig>
): StylePreset3DRuntime {
  const base = STYLE_RUNTIME_MAP[preset] || STYLE_RUNTIME_MAP.cinematic_3d;
  if (!custom) return base;
  return {
    ...base,
    keyLightColor: custom.keyLightColor ?? base.keyLightColor,
    keyLightIntensity: custom.keyLightIntensity ?? base.keyLightIntensity,
    fillLightColor: custom.fillLightColor ?? base.fillLightColor,
    fillLightIntensity: custom.fillLightIntensity ?? base.fillLightIntensity,
    rimLightColor: custom.rimLightColor ?? base.rimLightColor,
    rimLightIntensity: custom.rimLightIntensity ?? base.rimLightIntensity,
    fogColor: custom.fogColor ?? base.fogColor,
    fogDensity: custom.fogDensity ?? base.fogDensity,
    exposure: custom.exposure ?? base.exposure,
    roughnessBias: custom.roughnessBias ?? base.roughnessBias,
    metalnessBias: custom.metalnessBias ?? base.metalnessBias,
    headScale: custom.headScale ?? base.headScale,
    stopMotionFps: custom.stopMotionFps ?? base.stopMotionFps,
    toonMode: custom.toonMode ?? base.toonMode,
    outlineWidth: custom.outlineWidth ?? base.outlineWidth,
  };
}
